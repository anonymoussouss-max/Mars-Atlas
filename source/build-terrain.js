// Bakes the CTX DEM into a compact grid in image-% space: mean elevation, mean slope and 90th-percentile
// slope per cell (slopes measured at the DEM's native 20 m, then summarized).
// Usage: node scripts/build-terrain.js <dem.tif> <frame.json>
import { fromFile } from "geotiff";
import { readFileSync, writeFileSync } from "node:fs";
import { gzipSync } from "node:zlib";

const [demPath, framePath] = process.argv.slice(2);
const frame = JSON.parse(readFileSync(framePath, "utf8"));
const [a, b, c, d, e, f] = frame.affine;
const COLS = 320, ROWS = Math.round((COLS * frame.heightKm) / frame.widthKm);

const dem = await (await fromFile(demPath)).getImage();
const corners = [[0, 0], [100, 0], [0, 100], [100, 100]].map(([u, v]) => [a * u + b * v + c, d * u + e * v + f]);
const c0 = Math.floor(Math.min(...corners.map((p) => p[0]))) - 3, c1 = Math.ceil(Math.max(...corners.map((p) => p[0]))) + 3;
const r0 = Math.floor(Math.min(...corners.map((p) => p[1]))) - 3, r1 = Math.ceil(Math.max(...corners.map((p) => p[1]))) + 3;
const [z] = await dem.readRasters({ window: [c0, r0, c1, r1], samples: [0] });
const W = c1 - c0, H = r1 - r0;
const ok = (v) => Number.isFinite(v) && v > -20000 && v < 30000;

const det = a * e - b * d;
const sums = new Float64Array(COLS * ROWS), counts = new Uint16Array(COLS * ROWS);
const slopes = Array.from({ length: COLS * ROWS }, () => []);
const CELL = 20;
for (let y = 1; y < H - 1; y++) for (let x = 1; x < W - 1; x++) {
  const col = x + c0, row = y + r0;
  const u = (e * (col - c) - b * (row - f)) / det, v = (-d * (col - c) + a * (row - f)) / det;
  if (u < 0 || v < 0 || u >= 100 || v >= 100) continue;
  const i = y * W + x, n = [z[i - W - 1], z[i - W], z[i - W + 1], z[i - 1], z[i + 1], z[i + W - 1], z[i + W], z[i + W + 1]];
  if (!ok(z[i]) || !n.every(ok)) continue;
  const dzdx = (n[2] + 2 * n[4] + n[7] - n[0] - 2 * n[3] - n[5]) / (8 * CELL);
  const dzdy = (n[5] + 2 * n[6] + n[7] - n[0] - 2 * n[1] - n[2]) / (8 * CELL);
  const g = Math.floor((v / 100) * ROWS) * COLS + Math.floor((u / 100) * COLS);
  sums[g] += z[i]; counts[g]++;
  slopes[g].push((Math.atan(Math.hypot(dzdx, dzdy)) * 180) / Math.PI);
}

const elev = new Int16Array(COLS * ROWS), mean = new Uint8Array(COLS * ROWS), p90 = new Uint8Array(COLS * ROWS);
let empty = 0, steep20 = 0, steep30 = 0;
for (let g = 0; g < COLS * ROWS; g++) {
  if (!counts[g]) { empty++; elev[g] = -32768; continue; }
  const s = slopes[g].sort((p, q) => p - q);
  elev[g] = Math.round(sums[g] / counts[g]);
  mean[g] = Math.min(255, Math.round((s.reduce((t, v) => t + v, 0) / s.length) * 4));
  const q = s[Math.min(s.length - 1, Math.floor(s.length * 0.9))];
  p90[g] = Math.min(255, Math.round(q * 4));
  if (q >= 20) steep20++;
  if (q >= 30) steep30++;
}
const elevs = Array.from(elev).filter((v) => v > -32768);
console.log({ COLS, ROWS, cellMx: (frame.widthKm * 1000) / COLS, cellMy: (frame.heightKm * 1000) / ROWS, empty, minElev: Math.min(...elevs), maxElev: Math.max(...elevs), shareOver20deg: +(steep20 / (COLS * ROWS)).toFixed(3), shareOver30deg: +(steep30 / (COLS * ROWS)).toFixed(3) });

const raw = Buffer.concat([Buffer.from(elev.buffer), Buffer.from(mean.buffer), Buffer.from(p90.buffer)]);
const gz = gzipSync(raw, { level: 9 });
console.log("raw KB", Math.round(raw.length / 1024), "gz KB", Math.round(gz.length / 1024));
writeFileSync("src/data/terrain-grid.js", `// Generated by scripts/build-terrain.js from the USGS CTX DEM mosaic. Do not edit.\nexport const COLS = ${COLS};\nexport const ROWS = ${ROWS};\nexport const GRID_GZ_B64 = "${gz.toString("base64")}";\n`);
writeFileSync("src/data/jezero-frame.json", JSON.stringify({ ...frame, dem: { originX: 4329000, originY: 1143420, pixelM: 20, radiusM: 3396190, stdParallelDeg: 18.4663 } }, null, 1));
